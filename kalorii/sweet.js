const BY_NAME = ['аспартам', 'сукралоз', 'цикламат', 'сахарин', 'стевия', 'стевиол', 'эритрит', 'ксилит', 'сорбит', 'мальтит', 'изомальт', 'ацесульфам', 'неотам'];

export function sweetInfo(product) {
  const tags = (product.additives || []).map((t) => String(t).toLowerCase().replace(/^en:/, ''));
  const found = [...new Set(tags)].filter((t) => SWEET[t])
    .map((t) => ({ code: t, name: SWEET[t][0], note: SWEET[t][1], risk: SWEET[t][2] }));
  const ing = String(product.ingredients || '').toLowerCase();
  const inText = BY_NAME.filter((n) => ing.includes(n));
  const hasSugar = /\bсахар\b|сироп|глюкоз|фруктоз/.test(ing) && !inText.length;
  return { found, inText, hasSugar };
}
